"""Render short side-by-side samples: one UniMuMo sample vs the selected (and retimed) candidate.
A dot under each dancer flashes on music beats (orange) and on motion beats (blue).

Experiment A uses AIST music, which is not redistributed, so those samples are silent GIFs;
experiment B samples are MP4 files with the music generated by UniMuMo, plus the MP3.

python render_samples.py        # both experiments; or: python render_samples.py a
"""
import os
import pickle
import subprocess

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import soundfile as sf  # noqa: E402
from matplotlib.animation import FFMpegWriter, PillowWriter  # noqa: E402

from beats import motion_beats_speedmin  # noqa: E402
from make_tables import load_rows, select  # noqa: E402
from retime import retime  # noqa: E402

CHAIN = [[0, 2, 5, 8, 11], [0, 1, 4, 7, 10], [0, 3, 6, 9, 12, 15], [9, 14, 17, 19, 21], [9, 13, 16, 18, 20]]
INK, MUTED, BEAT, MOVE = "#0b0b0b", "#9a9893", "#eb6834", "#2a78d6"
OUT = "results/samples"
STEP = 3  # 60 fps -> 20 fps


def flash(frames, n, width=2):
    on = np.zeros(n, dtype=bool)
    for f in frames:
        on[f // STEP: f // STEP + width] = True
    return on


def animate(panels, path, audio=None):
    """panels: list of (title, joints (T,22,3), music beat frames)."""
    n = len(panels[0][1]) // STEP
    fig = plt.figure(figsize=(3.2 * len(panels), 3.6), facecolor="#fcfcfb")
    axes, lines, dots = [], [], []
    for k, (title, j, mb) in enumerate(panels):
        ax = fig.add_subplot(1, len(panels), k + 1, projection="3d")
        ax.set_facecolor("#fcfcfb")
        c = j[:, 0].mean(0)
        ax.set_xlim(c[0] - 0.9, c[0] + 0.9)
        ax.set_ylim(c[2] - 0.9, c[2] + 0.9)
        ax.set_zlim(0, 1.8)
        ax.view_init(elev=12, azim=-80)
        ax.dist = 6.2  # zoom in on the dancer
        ax.set_axis_off()
        ax.set_title(title, fontsize=9, color=INK)
        xx, zz = np.meshgrid([c[0] - 0.9, c[0] + 0.9], [c[2] - 0.9, c[2] + 0.9])
        ax.plot_surface(xx, zz, np.zeros_like(xx), color="#ecebe7", alpha=0.5)
        lines.append([ax.plot([], [], [], color=INK if i < 3 else "#52514e", lw=2)[0] for i in range(len(CHAIN))])
        mdot = fig.text((k + 0.38) / len(panels), 0.06, "●", color=MUTED, fontsize=14, ha="center")
        ddot = fig.text((k + 0.62) / len(panels), 0.06, "●", color=MUTED, fontsize=14, ha="center")
        fig.text((k + 0.38) / len(panels), 0.01, "music beat", color=MUTED, fontsize=7, ha="center")
        fig.text((k + 0.62) / len(panels), 0.01, "motion beat", color=MUTED, fontsize=7, ha="center")
        dots.append((mdot, ddot, flash(mb, n), flash(motion_beats_speedmin(j), n)))
        axes.append(ax)
    fig.subplots_adjust(left=0, right=1, bottom=0.08, top=0.9, wspace=0)

    def update(t):
        for (title, j, mb), ls, (mdot, ddot, mon, don) in zip(panels, lines, dots):
            p = j[t * STEP]
            for l, ch in zip(ls, CHAIN):
                l.set_data(p[ch, 0], p[ch, 2])
                l.set_3d_properties(p[ch, 1])
            mdot.set_color(BEAT if mon[t] else MUTED)
            ddot.set_color(MOVE if don[t] else MUTED)
        return []

    tmp = path + (".tmp.mp4" if audio is not None else "")
    writer = FFMpegWriter(fps=60 // STEP, bitrate=600) if audio is not None else PillowWriter(fps=60 // STEP)
    with writer.saving(fig, tmp, dpi=80):
        for t in range(n):
            update(t)
            writer.grab_frame(facecolor=fig.get_facecolor())
    plt.close(fig)
    if audio is not None:
        wav = path + ".tmp.wav"
        sf.write(wav, audio, 32000)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-i", wav, "-c:v", "copy",
                        "-c:a", "aac", "-b:a", "96k", "-shortest", path], check=True)
        os.remove(tmp)
        os.remove(wav)


def main(exps):
    os.makedirs(OUT, exist_ok=True)
    for exp, items in [("a", ["mHO5", "mLO2"]), ("b", ["disco_0", "hiphop_0"])]:
        if exp not in exps:
            continue
        df, _, jobs = load_rows(exp)
        chosen = select(df, "bas" if exp == "a" else "clap+bas", 16)
        sc = pickle.load(open(f"runs/exp_{exp}/scores.pkl", "rb"))
        for jid in items:
            d = np.load(f"runs/exp_{exp}/{jid}__s0.npz")
            joints = d["joints"].astype(np.float32)
            audio = d["audio"].astype(np.float32) / 32767
            c = chosen[(jid, 0)]
            mb0 = sc[(jid, 0)]["music_beats"][0]["beat"]
            mbc = sc[(jid, 0)]["music_beats"][c]["beat"]
            best = retime(joints[c], mbc)[0]
            if exp == "a":
                panels = [("UniMuMo, 1 sample", joints[0], mb0), ("best-of-16 + retime", best, mbc)]
                animate(panels, os.path.join(OUT, f"music2dance_{jid}.gif"))
            else:
                for name, title, j, a, mb in [("unimumo_1sample", "UniMuMo, 1 sample", joints[0], audio[0], mb0),
                                              ("bestof16_retime", "best-of-16 + retime", best, audio[c], mbc)]:
                    animate([(title, j, mb)], os.path.join(OUT, f"text2musicdance_{jid}_{name}.mp4"), a)
                    sf.write(os.path.join(OUT, f"text2musicdance_{jid}_{name}.mp3"), a, 32000)
            print("rendered", exp, jid, "chosen candidate", c, flush=True)


if __name__ == "__main__":
    import sys
    main(sys.argv[1:] or ["a", "b"])
